import Link from "next/link";
import { notFound } from "next/navigation";
import Checklist from "@/components/Checklist";
import OnComposio from "@/components/OnComposio";
import SetupKit from "@/components/SetupKit";
import { freshness } from "@/lib/freshness";
import ResearchForm from "@/components/ResearchForm";
import ShareBar from "@/components/ShareBar";
import { Cites, DIFF, EvidenceTag, OwnerTag, ROUTE_LABEL, Section } from "@/components/ui";
import { llmConfigured } from "@/lib/llm";
import { AUDIENCE_LABEL, type Claim } from "@/lib/schema";
import { getGuide } from "@/lib/store";

export const dynamic = "force-dynamic";

export async function generateMetadata({ params }: { params: Promise<{ id: string }> }) {
  const g = await getGuide((await params).id);
  return { title: g ? `${g.provider.name} OAuth guide · OAuth Launchpad` : "Guide not found" };
}

function ClaimLine({ c }: { c: Claim }) {
  return (
    <span>
      {c.text} <EvidenceTag e={c.evidence} />
      <Cites ids={c.sourceIds} />
    </span>
  );
}

export default async function GuidePage({ params }: { params: Promise<{ id: string }> }) {
  const g = await getGuide((await params).id);
  if (!g) notFound();
  const d = DIFF[g.summary.difficulty];
  const f = freshness(g);
  const recheck = `/research?${new URLSearchParams({ provider: g.provider.name, actions: g.useCase.actions, audience: g.useCase.audience, ...(g.kind === "seed" ? { base: g.id } : {}) })}`;

  return (
    <article className="grid min-w-0 gap-5 [&>*]:min-w-0">
      <div className="grid gap-2">
        <p className="text-sm text-muted">
          <Link href="/" className="underline">Guides</Link> / {g.provider.name}
        </p>
        <div className="flex flex-wrap items-end justify-between gap-3">
          <div>
            <h1 className="text-2xl font-semibold tracking-tight">{g.provider.name}: OAuth setup &amp; approval</h1>
            <p className="text-sm text-muted">
              For “{g.useCase.actions}” · {AUDIENCE_LABEL[g.useCase.audience]} ·{" "}
              {g.kind === "seed" ? "Starter guide, hand-researched" : "Generated by the research agent"} · {g.createdAt.slice(0, 10)}
            </p>
          </div>
          <ShareBar id={g.id} />
        </div>
        <p className="flex flex-wrap items-center gap-x-3 gap-y-1 text-xs text-muted">
          <span>
            Last verified {f.verified} ·{" "}
            <span className={f.due ? "font-semibold text-amber-700 dark:text-amber-300" : ""}>
              {f.due ? `review overdue since ${f.nextReview}` : `next review ${f.nextReview}`}
            </span>
          </span>
          <Link href={recheck} className="text-accent underline">Re-check now with the agent</Link>
          <a href={`/g/${g.id}/json`} className="underline">JSON for agents</a>
        </p>
        {g.review && (
          <div className="rounded-md border border-emerald-600/40 bg-emerald-50 p-3 text-sm text-emerald-900 dark:bg-emerald-950 dark:text-emerald-200">
            <p className="font-medium">
              Reviewed {g.review.date}: {g.review.confirmed} of {g.review.checked} spot-checked claims confirmed against the cited pages.
            </p>
            {g.review.notes.length > 0 && (
              <ul className="mt-1 list-disc pl-5 text-xs">
                {g.review.notes.map((n, i) => (
                  <li key={i}>{n}</li>
                ))}
              </ul>
            )}
          </div>
        )}
        {g.status === "partial" && (
          <p className="rounded-md bg-amber-50 p-3 text-sm text-amber-900 dark:bg-amber-950 dark:text-amber-200">
            Partial result: some key facts could not be confirmed. Gaps are listed under “Uncertain”.
          </p>
        )}
      </div>

      <p className="flex flex-wrap items-center gap-1.5 text-xs text-muted">
        How we know each claim:
        <EvidenceTag e="observed" /> seen in a setup attempt
        <EvidenceTag e="documented" /> quoted from official docs
        <EvidenceTag e="secondary" /> non-provider source
        <EvidenceTag e="inferred" /> reasoned from sources
        <EvidenceTag e="unverified" /> not confirmed
      </p>

      {/* Next action + summary */}
      <section className="rounded-lg border-2 border-accent bg-accent-soft p-5">
        <p className="text-xs font-semibold uppercase tracking-wide text-accent">Next action</p>
        <p className="mt-1 text-lg font-medium">{g.summary.nextAction}</p>
      </section>

      <div className="grid gap-4 md:grid-cols-3 [&>*]:min-w-0">
        <div className="rounded-lg border border-line bg-panel p-4">
          <p className="text-xs text-muted">Recommended route</p>
          <p className="font-semibold">{ROUTE_LABEL[g.summary.route]}</p>
          <p className="mt-1 text-sm text-muted">{g.summary.routeReason}</p>
          {g.summary.managedOAuth && (
            <p className="mt-2 border-t border-line pt-2 text-sm">
              <span className={`mr-1 text-xs font-semibold ${g.summary.managedOAuth.status === "available" ? "text-emerald-700 dark:text-emerald-300" : "text-muted"}`}>
                {g.summary.managedOAuth.status === "available" ? "Managed app available on Composio." : g.summary.managedOAuth.status === "not_listed" ? "Not Composio-managed." : "Managed status unknown."}
              </span>
              {g.summary.managedOAuth.text}
              <Cites ids={g.summary.managedOAuth.sourceIds} />
            </p>
          )}
        </div>
        <div className="rounded-lg border border-line bg-panel p-4">
          <p className="text-xs text-muted">Difficulty</p>
          <p className={`font-semibold ${d.cls}`}>{d.label}</p>
          <p className="mt-1 text-sm text-muted">{g.summary.difficultyReason}</p>
        </div>
        <div className="rounded-lg border border-line bg-panel p-4">
          <p className="text-xs text-muted">Main launch blocker</p>
          <p className="text-sm"><ClaimLine c={g.summary.mainBlocker} /></p>
          <p className="mt-2 text-xs text-muted">Testing before review</p>
          <p className="text-sm"><ClaimLine c={g.summary.testingBeforeReview} /></p>
        </div>
      </div>

      <Section title="Effort and timing" hint="Your hands-on work and the provider's wait are different things. They are shown separately.">
        <div className="grid gap-3 md:grid-cols-2">
          <div className="rounded-md border border-line p-3">
            <p className="text-xs font-semibold text-muted">YOUR ACTIVE WORK</p>
            <p className="mt-1 text-sm"><ClaimLine c={g.timing.activeWork} /></p>
          </div>
          <div className="rounded-md border border-line p-3">
            <p className="text-xs font-semibold text-muted">PROVIDER REVIEW WAIT</p>
            <p className="mt-1 text-sm"><ClaimLine c={g.timing.reviewWait} /></p>
          </div>
        </div>
        {(g.timing.policyDeadlines.length > 0 || g.timing.costs.length > 0) && (
          <ul className="mt-3 grid gap-2 text-sm">
            {g.timing.policyDeadlines.map((c, i) => (
              <li key={`d${i}`}><span className="font-medium">Policy deadline: </span><ClaimLine c={c} /></li>
            ))}
            {g.timing.costs.map((c, i) => (
              <li key={`c${i}`}><span className="font-medium">Cost: </span><ClaimLine c={c} /></li>
            ))}
          </ul>
        )}
      </Section>

      <div className="grid gap-5 md:grid-cols-2 [&>*]:min-w-0">
        <Section title="Prerequisites">
          <ul className="grid list-disc gap-2 pl-5 text-sm">
            {g.prerequisites.map((p, i) => <li key={i}><ClaimLine c={p} /></li>)}
            {!g.prerequisites.length && <li className="list-none text-muted">None identified.</li>}
          </ul>
        </Section>
        <Section title="What an agent can do vs. where you take over">
          <div className="grid gap-3 text-sm">
            <div>
              <p className="text-xs font-semibold text-muted">AGENT CAN</p>
              <ul className="mt-1 grid list-disc gap-1 pl-5">{g.agentVsHuman.agentCan.map((a, i) => <li key={i}>{a}</li>)}</ul>
            </div>
            <div>
              <p className="text-xs font-semibold text-muted">YOU (OR AN ADMIN) MUST</p>
              <ul className="mt-1 grid list-disc gap-1 pl-5">{g.agentVsHuman.humanMust.map((a, i) => <li key={i}>{a}</li>)}</ul>
            </div>
          </div>
        </Section>
      </div>

      {g.permissions.length > 0 && (
        <Section title="Permissions (scopes)" hint="The smallest set that still supports your use case, and what each does to review.">
          <div className="overflow-x-auto">
            <table className="w-full text-left text-sm">
              <thead className="text-xs text-muted">
                <tr><th className="py-1 pr-3">Scope</th><th className="py-1 pr-3">Enables</th><th className="py-1 pr-3">Review impact</th><th className="py-1">Evidence</th></tr>
              </thead>
              <tbody>
                {g.permissions.map((p) => (
                  <tr key={p.scope} className="border-t border-line align-top">
                    <td className="py-2 pr-3 font-mono text-xs break-all">{p.scope}</td>
                    <td className="py-2 pr-3">{p.enables}</td>
                    <td className="py-2 pr-3">{p.reviewImpact}</td>
                    <td className="py-2"><EvidenceTag e={p.evidence} /><Cites ids={p.sourceIds} /></td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        </Section>
      )}

      <Section id="setup-kit" title="Let the agent start it" hint="The registration work an agent can do before you sign in: a prefilled link where the provider documents one, and every form value ready to paste.">
        <SetupKit guide={g} />
      </Section>

      <Section title="Checklist" hint="Steps grouped by stage. Each shows who owns it and how we know it.">
        <Checklist guide={g} />
      </Section>

      <OnComposio guide={g} />

      {g.blockers.length > 0 && (
        <Section title="Blockers and recovery">
          <ul className="grid gap-3">
            {g.blockers.map((b, i) => (
              <li key={i} className="rounded-md border border-line p-3 text-sm">
                <p className="flex flex-wrap items-center gap-1.5 font-medium">
                  {b.symptom} <OwnerTag o={b.owner} /> <EvidenceTag e={b.evidence} /><Cites ids={b.sourceIds} />
                </p>
                <p className="mt-1 text-muted"><span className="font-medium text-fg">Likely cause:</span> {b.cause}</p>
                <p className="mt-0.5"><span className="font-medium">Next:</span> {b.nextAction}</p>
              </li>
            ))}
          </ul>
        </Section>
      )}

      {(g.uncertainties.length > 0 || g.conflicts.length > 0) && (
        <Section id="uncertain" title="Uncertain or conflicting">
          <ul className="grid list-disc gap-1 pl-5 text-sm">
            {g.conflicts.map((c, i) => <li key={`c${i}`}><span className="font-medium">Conflict:</span> {c}</li>)}
            {g.uncertainties.map((u, i) => <li key={`u${i}`}>{u}</li>)}
          </ul>
        </Section>
      )}

      <Section id="evidence" title="Evidence" hint="What we tested, and the sources behind each claim.">
        {g.attempts.length > 0 && (
          <details open className="mb-4">
            <summary className="text-sm font-semibold">Setup attempts ({g.attempts.length})</summary>
            <ul className="mt-2 grid gap-2">
              {g.attempts.map((a, i) => (
                <li key={i} className="rounded-md border border-line p-3 text-sm">
                  <p className="font-medium">{a.intended} <span className="text-xs font-normal text-muted">· {a.date}</span></p>
                  <p className="mt-1 font-mono text-xs break-all">{a.attempted}</p>
                  <p className="mt-1"><span className="text-muted">Result:</span> {a.result}</p>
                  <p><span className="text-muted">Stopped at:</span> {a.stoppedAt}</p>
                  <p><span className="text-muted">Proves:</span> {a.proves}</p>
                  <p><span className="text-muted">Does not prove:</span> {a.doesNotProve}</p>
                  {a.correction && <p><span className="text-muted">Correction made:</span> {a.correction}</p>}
                </li>
              ))}
            </ul>
          </details>
        )}
        <ol className="grid gap-2 text-sm">
          {g.sources.map((s) => (
            <li key={s.id} id={`src-${s.id}`} className="scroll-mt-20 rounded-md border border-line p-3">
              <p className="flex flex-wrap items-baseline gap-2">
                <span className="font-mono text-xs">[{s.id}]</span>
                <a href={s.url} target="_blank" rel="noreferrer" className="font-medium text-accent underline break-all">{s.title}</a>
                <span className="text-xs text-muted">{s.type} · retrieved {s.retrieved}</span>
              </p>
              {s.note && <p className="mt-1 border-l-2 border-line pl-2 text-muted">“{s.note}”</p>}
            </li>
          ))}
        </ol>
        {g.researchLog.length > 0 && (
          <details className="mt-4">
            <summary className="text-sm font-semibold">Research log ({g.researchLog.length} events)</summary>
            <ol className="mt-2 grid list-decimal gap-0.5 pl-5 font-mono text-xs text-muted">
              {g.researchLog.map((l, i) => <li key={i} className="break-all">{l}</li>)}
            </ol>
          </details>
        )}
      </Section>

      {llmConfigured() && (
        <Section title="Different use case?" hint="Re-run the research agent for your own actions and audience. It starts from this guide's official sources.">
          <ResearchForm
            compact
            initialProvider={g.provider.name}
            initialActions=""
            initialAudience={g.useCase.audience}
            baseGuideId={g.kind === "seed" ? g.id : undefined}
          />
        </Section>
      )}
    </article>
  );
}
