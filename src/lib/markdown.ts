import { AUDIENCE_LABEL, type Claim, type Guide } from "./schema";

const ROUTE: Record<Guide["summary"]["route"], string> = {
  managed: "Use a managed OAuth app",
  own_app: "Register your own OAuth app",
  unresolved: "Unresolved: needs more investigation",
};

export function toMarkdown(g: Guide, url = ""): string {
  const cite = (ids: string[]) =>
    ids.length ? " " + ids.map((id) => `[${id}]`).join("") : "";
  const c = (x: Claim) => `${x.text} _(${x.evidence})_${cite(x.sourceIds)}`;
  const L: string[] = [];
  L.push(`# ${g.provider.name}: OAuth setup and approval guide`);
  L.push("");
  L.push(`**Use case:** ${g.useCase.actions} · **Audience:** ${AUDIENCE_LABEL[g.useCase.audience]}`);
  L.push(`**Status:** ${g.status}${g.kind === "generated" ? " (generated by research agent)" : " (starter guide)"} · ${g.createdAt.slice(0, 10)}${url ? ` · ${url}` : ""}`);
  L.push("");
  L.push(`## Next action\n${g.summary.nextAction}`);
  L.push("");
  L.push(`## Summary`);
  L.push(`- **Route:** ${ROUTE[g.summary.route]}. ${g.summary.routeReason}`);
  if (g.summary.managedOAuth) L.push(`- **Managed OAuth (Composio):** ${g.summary.managedOAuth.status}. ${g.summary.managedOAuth.text}${cite(g.summary.managedOAuth.sourceIds)}`);
  L.push(`- **Difficulty:** ${g.summary.difficulty}. ${g.summary.difficultyReason}`);
  L.push(`- **Testing before review:** ${c(g.summary.testingBeforeReview)}`);
  L.push(`- **Main launch blocker:** ${c(g.summary.mainBlocker)}`);
  L.push("");
  L.push(`## Effort and timing`);
  L.push(`- **Your active work:** ${c(g.timing.activeWork)}`);
  L.push(`- **Provider review wait:** ${c(g.timing.reviewWait)}`);
  g.timing.policyDeadlines.forEach((d) => L.push(`- **Policy deadline:** ${c(d)}`));
  g.timing.costs.forEach((d) => L.push(`- **Cost:** ${c(d)}`));
  if (g.prerequisites.length) {
    L.push("", `## Prerequisites`);
    g.prerequisites.forEach((p) => L.push(`- ${c(p)}`));
  }
  if (g.permissions.length) {
    L.push("", `## Permissions`);
    g.permissions.forEach((p) => L.push(`- \`${p.scope}\`: ${p.enables}. Review impact: ${p.reviewImpact} _(${p.evidence})_${cite(p.sourceIds)}`));
  }
  for (const ph of g.phases) {
    L.push("", `## ${ph.name}`);
    ph.steps.forEach((s) => {
      L.push(`- [ ] **${s.title}** (${s.owner}, ${s.evidence})${cite(s.sourceIds)}`);
      if (s.detail) L.push(`  ${s.detail}`);
      if (s.where) L.push(`  Where: ${s.where}`);
      if (s.outcome) L.push(`  Outcome: ${s.outcome}`);
      if (s.dependsOn.length) L.push(`  After: ${s.dependsOn.join(", ")}`);
    });
  }
  if (g.blockers.length) {
    L.push("", `## Blockers and recovery`);
    g.blockers.forEach((b) =>
      L.push(`- **${b.symptom}**. Cause: ${b.cause}. Next: ${b.nextAction} (owner: ${b.owner}, ${b.evidence})${cite(b.sourceIds)}`),
    );
  }
  L.push("", `## What an agent can do vs. where you take over`);
  g.agentVsHuman.agentCan.forEach((a) => L.push(`- Agent: ${a}`));
  g.agentVsHuman.humanMust.forEach((a) => L.push(`- You: ${a}`));
  if (g.attempts.length) {
    L.push("", `## Setup attempts`);
    g.attempts.forEach((a) =>
      L.push(`- ${a.date}: ${a.attempted} → ${a.result}. Stopped at: ${a.stoppedAt}. Proves: ${a.proves}. Does not prove: ${a.doesNotProve}.${a.correction ? ` Correction: ${a.correction}` : ""}`),
    );
  }
  if (g.uncertainties.length || g.conflicts.length) {
    L.push("", `## Uncertain or conflicting`);
    g.uncertainties.forEach((u) => L.push(`- ${u}`));
    g.conflicts.forEach((u) => L.push(`- Conflict: ${u}`));
  }
  L.push("", `## Sources`);
  g.sources.forEach((s) => L.push(`- [${s.id}] ${s.title} (${s.type}, retrieved ${s.retrieved}): ${s.url}${s.note ? `\n  > ${s.note}` : ""}`));
  L.push("", "_Evidence labels: observed = seen in a setup attempt; documented = quoted from official docs; secondary = non-provider source; inferred = reasoned from sources; unverified = not confirmed._");
  return L.join("\n");
}
